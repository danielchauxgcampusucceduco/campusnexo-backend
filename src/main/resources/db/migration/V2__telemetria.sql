-- Aggregated readings of each space. people_count is the occupancy recorded for the room (for camera frames, the
-- twin's fused estimate); camera_people is the camera's own count in that frame, kept apart so the AI service fuses
-- raw measurements. One reading per space and instant: a redelivered message cannot create a second row.
CREATE TABLE telemetry_stream (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id VARCHAR(32) NOT NULL REFERENCES spaces (space_id),
    recorded_at TIMESTAMPTZ NOT NULL,
    people_count INTEGER NOT NULL CHECK (people_count >= 0),
    object_count INTEGER NOT NULL CHECK (object_count >= 0),
    wifi_devices INTEGER NOT NULL CHECK (wifi_devices >= 0),
    co2_ppm DOUBLE PRECISION NOT NULL CHECK (co2_ppm >= 0),
    temperature_c DOUBLE PRECISION NOT NULL,
    humidity_pct DOUBLE PRECISION NOT NULL CHECK (humidity_pct BETWEEN 0 AND 100),
    illuminance_lux DOUBLE PRECISION NOT NULL CHECK (illuminance_lux >= 0),
    active_power_kw DOUBLE PRECISION NOT NULL CHECK (active_power_kw >= 0),
    camera_people INTEGER CHECK (camera_people >= 0),
    CONSTRAINT uq_telemetry_space_instant UNIQUE (space_id, recorded_at)
);
